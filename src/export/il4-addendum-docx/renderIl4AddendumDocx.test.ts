import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { frameworkRegistry } from "@/data/framework";
import { createProjectMetadata } from "@/data/project";
import { readZipTextEntries } from "@/export/ssp-docx/readPackage";
import { renderIl4AddendumDocx } from "@/export/il4-addendum-docx";
import { DOD_CLOUD_IL4_FRAMEWORK_ID } from "@/framework/dod-cloud-il4-rev5/identities";
import { buildIl4AddendumDocument } from "@/il4-addendum";
import type { StoredProject } from "@/persistence/types";
import type { EvidenceWithControlIds } from "@/data/evidence";
import { DEMO_IL4_PARAMETER_RECORDS } from "@/seed/demo/parameter-records";

const GENERATED_AT = "2026-09-28T15:00:00.000Z";

function documentText(xml: string): string {
  return [...xml.matchAll(/<w:t(?:\s[^>]*)?>([^<]*)<\/w:t>/g)]
    .map((match) => match[1] ?? "")
    .join("")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}

function sampleDocument() {
  const project: StoredProject = {
    id: "project-il4",
    name: "Snow Goose Cloud Impact Level 4 (Demo)",
    organizationId: "org-1",
    frameworkId: DOD_CLOUD_IL4_FRAMEWORK_ID,
    schemaVersion: 3,
    revision: 4,
    createdAt: GENERATED_AT,
    updatedAt: GENERATED_AT,
    metadata: createProjectMetadata({
      systemName: "Snow Goose Cloud Impact Level 4",
      organizationName: "Canadian Goose Defence System",
      systemDescription: "Fictional Goose cloud offering.",
    }),
    implementations: {
      "grr-1": {
        status: "implemented",
        narrative: "CAC authentication is documented for operators.",
      },
    },
    parameterRecords: DEMO_IL4_PARAMETER_RECORDS,
  };
  const evidence: EvidenceWithControlIds = {
    id: "ev-1",
    projectId: project.id,
    title: "Snow Goose Cloud DoD PKI authentication note",
    description: "Demo note.",
    owner: "Priya Sharma",
    evidenceType: "document",
    status: "active",
    collectionDate: "2026-05-01",
    reviewDueDate: null,
    currentVersionId: null,
    createdAt: GENERATED_AT,
    updatedAt: GENERATED_AT,
    controlIds: ["grr-1"],
  };
  return buildIl4AddendumDocument({
    project,
    framework: frameworkRegistry.require(DOD_CLOUD_IL4_FRAMEWORK_ID).getFramework(),
    descriptor: frameworkRegistry.requireDescriptor(DOD_CLOUD_IL4_FRAMEWORK_ID),
    controlRecordsByControlId: new Map(),
    evidenceByControlId: new Map([["grr-1", [evidence]]]),
    generatedAt: GENERATED_AT,
  });
}

describe("renderIl4AddendumDocx", () => {
  it("writes a valid addendum package for the accepted delta", async () => {
    const document = sampleDocument();
    const started = Date.now();
    const buffer = await renderIl4AddendumDocx(document);
    const durationMs = Date.now() - started;
    assert.ok(durationMs < 15000, `generation took ${durationMs}ms`);
    assert.ok(buffer.byteLength > 5000);
    const files = readZipTextEntries(buffer);
    assert.ok(files.has("[Content_Types].xml"));
    assert.ok(files.has("word/document.xml"));
    assert.ok(files.has("word/_rels/document.xml.rels"));
    assert.equal(
      [...files.keys()].some((name) => name.startsWith("word/media/")),
      false,
    );
    const text = documentText(files.get("word/document.xml") ?? "");
    assert.match(text, /DoD IL4 System Security Plan Addendum/);
    assert.match(text, /cf-il4-addendum-docx/);
    assert.match(text, /Generated by Control Freak/);
    assert.match(text, /Snow Goose Cloud Impact Level 4/);
    assert.match(text, /Detailed DoD General Requirements/);
    assert.match(text, /32 \+ 1 \+ 312 = 345/);
    assert.match(text, /not out of scope/);
    for (const entry of document.grrs) {
      assert.ok(
        text.includes(`${entry.item.displayId} ${entry.item.title}`),
        entry.item.displayId,
      );
    }
    assert.match(text, /DoD PKI/);
    assert.doesNotMatch(text, /GR-15/);
    assert.doesNotMatch(text, /\bGR-10\b/);
    for (const family of document.nistFamilies) {
      for (const entry of family.entries) {
        assert.ok(
          text.includes(`${entry.item.displayId} ${entry.item.title}`),
          `missing ${entry.item.displayId}`,
        );
      }
    }
    assert.match(text, /SC-18 membership/);
    assert.match(text, /inclusion-only/);
    assert.doesNotMatch(text, /AC-1 Policy and Procedures/);
    assert.doesNotMatch(text, /AC-2 Account Management/);
    assert.match(text, /DoD assignment required/);
    assert.match(text, /Source interpretation requires review/);
    assert.match(text, /has not chosen a winner/);
    assert.match(text, /Cross Domain Solution/);
    assert.match(text, /Not present in the FedRAMP Moderate baseline/);
    assert.match(text, /DoD Rev\. 5 SSP Addendum/);
    assert.match(text, /does not mean DoD authored/);
    assert.match(text, /Snow Goose Cloud DoD PKI authentication note/);
    assert.match(text, /not been independently assessed or validated/);
    assert.doesNotMatch(text, /proves implementation|establishes compliance|UNCLASSIFIED/i);
    assert.match(text, /NIST SP 800-53/);
    assert.match(text, /FedRAMP Security Controls Baseline/);
    assert.match(text, /\[Not yet documented: Authorization boundary\]/);
    assert.match(text, /not a claim that none exist/);
    assert.match(text, /Word refreshes this table of contents/);
    assert.match(text, /Implementation response/);
    assert.match(text, /System Security Plan Addendum/);
    assert.doesNotMatch(text, /_odp/);
    assert.doesNotMatch(text, /authoritative value required/);
    assert.doesNotMatch(text, /control-level value is not mapped/);
    assert.match(text, /not used as the requirement value/);
    assert.match(text, /does not resolve the source conflict/);
  });
});
